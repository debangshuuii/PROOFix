/**
 * Synthetic API Payload Generator
 * Generates structured JSON mock bodies, query strings, and headers
 * for probing discovered API endpoints during browser and headless tests.
 */

import type { HttpMethod, SyntheticPayload } from '../types/api-endpoint-agent.ts';

/**
 * Generates appropriate synthetic request payloads based on HTTP method and path semantics.
 */
export function generateSyntheticPayload(
  endpointPath: string,
  method: HttpMethod = 'GET'
): SyntheticPayload {
  const headers: Record<string, string> = {
    'User-Agent': 'PROOFix-Api-Verifier/1.0',
    Accept: 'application/json, text/plain, */*',
  };

  if (method === 'GET' || method === 'DELETE') {
    return {
      method,
      headers,
    };
  }

  // POST / PUT / PATCH payloads
  headers['Content-Type'] = 'application/json';

  let body: Record<string, any> = {
    testProbe: true,
    timestamp: new Date().toISOString(),
  };

  const lower = endpointPath.toLowerCase();

  if (lower.includes('auth') || lower.includes('login') || lower.includes('session')) {
    body = {
      email: 'verifier@proofix.dev',
      username: 'test_verifier',
      password: 'SamplePassword123!',
    };
  } else if (lower.includes('user') || lower.includes('profile')) {
    body = {
      name: 'Verification Probe User',
      email: 'probe@proofix.dev',
      role: 'viewer',
    };
  } else if (lower.includes('item') || lower.includes('product') || lower.includes('data')) {
    body = {
      title: 'Verification Probe Item',
      description: 'Synthetic payload generated by PROOFix testing agent',
      quantity: 1,
      active: true,
    };
  }

  return {
    method,
    headers,
    body: JSON.stringify(body),
  };
}
